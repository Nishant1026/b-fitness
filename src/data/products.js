// ================================================================
// REUSABLE HELPER FUNCTIONS (ALL OPERATE ON THE CENTRAL ARRAY)
// ================================================================

export function getProductBySlug(slug) {
  if (!slug) return null
  const cleanSlug = slug.toLowerCase().trim()
  return products.find(p => p.slug.toLowerCase() === cleanSlug) || null
}

export function getProductsByCategory(category) {
  if (!category || category === 'all') return products
  const cat = category.toLowerCase().trim()
  if (cat === 'sale') return getSaleProducts()
  return products.filter(p => p.category.toLowerCase() === cat)
}

export function getProductsBySubcategory(category, subcategory) {
  if (!category) return products
  const cat = category.toLowerCase().trim()
  if (!subcategory) return getProductsByCategory(cat)
  const sub = subcategory.toLowerCase().trim()
  return products.filter(p =>
    p.category.toLowerCase() === cat &&
    (p.subcategory.toLowerCase() === sub || p.subcategory.toLowerCase().replace(/[\s&/]+/g, '-') === sub)
  )
}

export function getSaleProducts() {
  return products.filter(p => p.sale === true)
}

export function searchProducts(query) {
  if (!query || !query.trim()) return products
  const q = query.toLowerCase().trim()
  return products.filter(p =>
    p.name.toLowerCase().includes(q) ||
    p.category.toLowerCase().includes(q) ||
    p.subcategory.toLowerCase().includes(q) ||
    p.categoryName.toLowerCase().includes(q) ||
    p.sku.toLowerCase().includes(q) ||
    p.description.toLowerCase().includes(q) ||
    p.shortDescription.toLowerCase().includes(q)
  )
}

export function getRelatedProducts(product, limit = 4) {
  if (!product) return []
  return products
    .filter(p =>
      p.id !== product.id &&
      (p.subcategory === product.subcategory || p.category === product.category)
    )
    .slice(0, limit)
}

export default products
